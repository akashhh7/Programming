#include<iostream>
using namespace std;

int main(){
    
    //integer variable
    int numberOfPirates = 10;
    cout<<"Number of pirates: "<<numberOfPirates<<endl;

    //character variable
    char firstLetterOfShip = 'G';
    cout<<"First letter of ship: "<<firstLetterOfShip<<endl;

    //floating variable, used for decimals
    float priceOfBerries = 4.99;
    cout<<"Price of berries: "<<priceOfBerries<<endl;

    //double floating variable, used for higher decimals
    double priceOfShip = 299.845;
    cout<<"Price of the ship: "<<priceOfShip<<endl;

    //string variable
    string pirateKing = "Luffy";
    cout<<"Pirate King: "<<pirateKing<<endl;

    //boolen variable
    bool luffyGonnaBePirateKing = true;
    cout<<"Luffy gonna be the pirate king (true/false): "<<luffyGonnaBePirateKing<<endl;
    
    bool blackbeardGonnaBePirateKing = false;
    cout<<"Blackbeard gonna be the pirate king (true/false): "<<blackbeardGonnaBePirateKing<<endl;

    return 0;
}