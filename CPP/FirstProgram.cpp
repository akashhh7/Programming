#include<iostream> //iostream is a header file here.
using namespace std; //this is used so that we dont have to write std::cout every time we want to print something.

//this is the main function where the execution of the program begins.
int main(){
    //cout is used to print something on the screen.
    cout<<"Hello World"<<endl;

    //endl is used to print a new line.
    
    cout<<"Hello"<<endl<<"World";
    
    //this is used to return a value from the main function.
    return 0;

}
